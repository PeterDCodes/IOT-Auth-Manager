import database from "./database.js"
import crypto from "crypto"
import bcrypt from "bcrypt"

const SALT_ROUNDS = 12

//Create key and register new device
/**
 * @param {Object} device - Device registration information.
 * @param {number} device.id device id
 * @param {string} device.name name of the device
 * @param {string} device.serial device serial number
 * @param {string} device.mac_addr MAC address of device
 * @param {string} device.device_ip static IP
 */
export const registerNewDevice=async({id, name, serial, mac_addr, device_ip})=>{
  try {
    const device = await getDeviceById(id)
    if(device && device.active === true){
      throw new Error("Active Device with Duplicate id exists")
    }

    const key = makeKey()
    const hashed_key = await makeHash(key)
    await addDevice(id, name, serial, mac_addr, device_ip, hashed_key)

    return key
  } catch(error) {
    throw new Error("Failed to register Device", {cause: error})
  }
}

//Insert Device into DB
/**
 * @param {number} id device id
 * @param {string} name name of the device
 * @param {string} serial device serial number
 * @param {string} mac_addr MAC address of device
 * @param {string} device_ip static IP
 * @param {string} hashed_key hashed key value generated by server
 */
export const addDevice=async(id, name, serial, mac_addr, device_ip, hashed_key)=>{
  await database.query(`
    INSERT INTO devices (
      id,
      name,
      serial,
      mac_addr,
      device_ip,
      hashed_key
    ) VALUES ($1, $2, $3, $4, $5, $6)
  `, [id, name, serial, mac_addr, device_ip, hashed_key])
}

//Method to query a single device for authentication
export const getDeviceById=async(id)=>{
  const result = await database.query(`
    SELECT *
    FROM devices
    WHERE id = $1
  `, [id])

  return result.rows[0]
}

//Method to query a single device without exposing its secret hash
export const getPublicDeviceById=async(id)=>{
  const result = await database.query(`
    SELECT id, name, serial, mac_addr, device_ip, dt_created, dt_modified, active
    FROM devices
    WHERE id = $1
  `, [id])

  return result.rows[0]
}

//Method to query all devices without exposing secret hashes
export const getDevices=async()=>{
  const result = await database.query(`
    SELECT id, name, serial, mac_addr, device_ip, dt_created, dt_modified, active
    FROM devices
    ORDER BY id
  `)

  return result.rows
}

//Hash Key
export const makeHash=async(secret)=>{
  return bcrypt.hash(secret, SALT_ROUNDS)
}

//Validate Key
export const validateHash=async(secret, hash)=>{
  return bcrypt.compare(secret, hash)
}

//Build client key
export const makeKey=()=>{
  return crypto.randomBytes(32).toString("hex")
}
