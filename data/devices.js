import database from "./database.js"
import crypto from "crypto"


//Create key and register new device
/**
 * @param {Object} device - Device registration information.
 * @param {number} device.id device id
 * @param {string} device.name name of the device
 * @param {string} device.serial device serial number
 * @param {string} device.mac_addr MAC address of device
 * @param {string} device.device_ip static IP
*/
export const registerNewDevice=async({id, name, serial, mac_addr, device_ip})=>{
    //TODO error handling

    //Check if device exists
    try{
        const device = getDeviceById(id)
        if(device && device.active == 1){
            throw new Error("Active Device with Duplicate id exists")
        }

        //Create Key
        const key = makeKey();
        //Hash key
        const hashed_key = await makeHash(key);
        //Store new device registration into DB
        addDevice(id, name, serial, mac_addr, device_ip, hashed_key)
        //Return original key to client
        return key;
    }catch(error){
        throw new Error("Failed to register Device", {cause: error})
    }

}

//Insert Device into DB
/**
 * @param {number} id device id
 * @param {string} name name of the device
 * @param {string} serial device serial number
 * @param {string} mac_addr MAC address of device
 * @param {string} device_ip static IP
 * @param {string} hashed_key hashed key value generated by server
*/
export const addDevice=(id, name, serial, mac_addr, device_ip, hashed_key)=>{

    //Create Timestamp of device creation
    const dt_created = getTime()
    //Set active
    const active = 1
    //dt_modified will remain null until modified
    const dt_modified = null

    // // Create a prepared statement to insert data into the database.
    const insert = database.prepare(`
        INSERT INTO devices (
        id, 
        name, 
        serial, 
        mac_addr, 
        device_ip, 
        hashed_key, 
        dt_created, 
        dt_modified, 
        active
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ? , ?)`);
    // // Execute the prepared statement with bound values.
    insert.run(id, name, serial, mac_addr, device_ip, hashed_key, dt_created, dt_modified, active);
}


//Method to query single device by ID
export const getDeviceById=(id)=>{

    //todo ID validation
    // Create a prepared statement to read data from the database.
    const query = database.prepare(`
    SELECT *
    FROM devices
    WHERE id = ?
    `);
    
    return query.get(id);

}


//Method to query all devices in the table
export const getDevices=()=>{
    // Create a prepared statement to read data from the database.
    const query = database.prepare('SELECT * FROM devices ORDER BY id');
    // Execute the prepared statement and log the result set.
    return(query.all());
}


//HELPER METHODS

//Helper utility for hashing and unhashing a key
import bcrypt from "bcrypt";
const SALT_ROUNDS = 12;
// Hash Key
/**
*@param {string} secret secret key valur
*@return {string} hashed secret
*/
export const makeHash=async(secret)=>{
    const hash = await bcrypt.hash(secret, SALT_ROUNDS);
    return hash
}
//Validate Key when given by user as part of auth
export const validateHash=async(secret, hash)=>{
    const isValid = await bcrypt.compare(secret, hash);

    return isValid;
}

//Build client key
export const makeKey=()=>{
    //Generate random key for user
    const key = crypto.randomBytes(32).toString('hex'); // Generates 64 hex characters
    return key;
}

/**
 * @return {string} UTC timestamp now
 */
const getTime=()=>{
    return Date.now().toString()
}


